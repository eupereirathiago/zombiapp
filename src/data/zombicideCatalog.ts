export function getDangerLevel(xp: number): DangerLevel {
  if (xp >= 43) return 'RED';
  if (xp >= 19) return 'ORANGE';
  if (xp >= 7) return 'YELLOW';
  return 'BLUE';
}

export function getDangerLevelLabel(level: DangerLevel): string {
  switch (level) {
    case 'BLUE':
      return 'Nível Azul';
    case 'YELLOW':
      return 'Nível Amarelo';
    case 'ORANGE':
      return 'Nível Laranja';
    case 'RED':
      return 'Nível Vermelho';
  }
}

export function calculateSurvivorCapabilities(
  character: GameCharacter,
  xp: number,
  selectedSkills: { orange: string | null; red: string | null }
) {
  const level = getDangerLevel(xp);
  const activeSkills: SkillDefinition[] = [character.skills.blue];

  if (level === 'YELLOW' || level === 'ORANGE' || level === 'RED') {
    activeSkills.push(character.skills.yellow);
  }
  if ((level === 'ORANGE' || level === 'RED') && selectedSkills.orange) {
    const orangeSkill = character.skills.orange.find((s) => s.id === selectedSkills.orange);
    if (orangeSkill) activeSkills.push(orangeSkill);
  }
  if (level === 'RED' && selectedSkills.red) {
    const redSkill = character.skills.red.find((s) => s.id === selectedSkills.red);
    if (redSkill) activeSkills.push(redSkill);
  }

  let maxActions = 3;
  let freeMoveActions = 0;
  let zonesPerMove = 1;
  let hasAmbidextrous = false;
  let hasSlippery = false;
  let meleeDiceBonus = 0;
  let rangedDiceBonus = 0;
  let meleeRollPlus = 0;
  let rangedRollPlus = 0;

  for (const skill of activeSkills) {
    if (skill.effectType === 'EXTRA_ACTION') {
      maxActions += skill.bonusValue || 1;
    }
    if (skill.effectType === 'FREE_MOVE') {
      freeMoveActions += skill.bonusValue || 1;
    }
    if (skill.effectType === 'DOUBLE_ZONES_PER_MOVE') {
      zonesPerMove = 2;
    }
    if (skill.effectType === 'AMBIDEXTROUS') {
      hasAmbidextrous = true;
    }
    if (skill.effectType === 'SLIPPERY') {
      hasSlippery = true;
    }
    if (skill.effectType === 'DICE_BONUS_MELEE') {
      meleeDiceBonus += skill.bonusValue || 1;
    }
    if (skill.effectType === 'DICE_BONUS_RANGED') {
      rangedDiceBonus += skill.bonusValue || 1;
    }
    if (skill.effectType === 'DICE_BONUS_COMBAT') {
      meleeDiceBonus += skill.bonusValue || 1;
      rangedDiceBonus += skill.bonusValue || 1;
    }
    if (skill.effectType === 'ROLL_PLUS_MELEE') {
      meleeRollPlus += skill.bonusValue || 1;
    }
    if (skill.effectType === 'ROLL_PLUS_RANGED') {
      rangedRollPlus += skill.bonusValue || 1;
    }
    if (skill.effectType === 'ROLL_PLUS_COMBAT') {
      meleeRollPlus += skill.bonusValue || 1;
      rangedRollPlus += skill.bonusValue || 1;
    }
  }

  return {
    level,
    activeSkills,
    maxActions,
    freeMoveActions,
    zonesPerMove,
    hasAmbidextrous,
    hasSlippery,
    meleeDiceBonus,
    rangedDiceBonus,
    meleeRollPlus,
    rangedRollPlus,
  };
}
